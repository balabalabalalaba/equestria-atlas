FONTS = {
    'normal': {'glyphs': _N, 'height': 7, 'line': 10, 'space': 1, 'upper': False},
    'tiny': {'glyphs': _T, 'height': 5, 'line': 6, 'space': 1, 'upper': True},
}

_cache = {}


def _glyph(font, ch):
    key = (font, ch)
    g = _cache.get(key)
    if g is None:
        f = FONTS[font]
        rows = f['glyphs'].get(ch)
        if rows is None:
            rows = f['glyphs'].get(ch.upper()) or f['glyphs']['?']
        w = max(len(r) for r in rows)
        g = np.zeros((len(rows), w), bool)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                g[y, x] = c == '#'
        _cache[key] = g
    return g


def text_width(s, font='normal', scale=1, spacing=None):
    f = FONTS[font]
    if f['upper']:
        s = s.upper()
    sp = f['space'] if spacing is None else spacing
    lines = s.split('\n')
    best = 0
    for ln in lines:
        wsum = sum(_glyph(font, ch).shape[1] + sp for ch in ln) - (sp if ln else 0)
        best = max(best, wsum)
    return best * scale


def _render_mask(s, font, spacing):
    f = FONTS[font]
    sp = f['space'] if spacing is None else spacing
    w = text_width(s, font, 1, spacing)
    h = f['height'] + 2  # room for descenders
    m = np.zeros((h, max(1, w)), bool)
    x = 0
    for ch in s:
        g = _glyph(font, ch)
        gh, gw = g.shape
        m[:gh, x:x + gw] |= g
        x += gw + sp
    return m


def text(canvas, x, y, s, color='white', font='normal', scale=1, align='left',
         shadow=None, outline=None, spacing=None, line_height=None):
    """Draw text with its top-left (or top-centre / top-right per `align`) at (x, y).

    shadow: colour of a 1px (x scale) drop shadow down-right.
    outline: colour of a 1px (x scale) 8-way outline.
    Returns the rendered width in pixels.
    """
    f = FONTS[font]
    if f['upper']:
        s = s.upper()
    lh = (line_height or f['line']) * scale
    maxw = 0
    for i, ln in enumerate(s.split('\n')):
        m = _render_mask(ln, font, spacing)
        if scale > 1:
            m = np.repeat(np.repeat(m, scale, 0), scale, 1)
        w = m.shape[1] if ln else 0
        maxw = max(maxw, w)
        lx = int(x) - (w // 2 if align == 'center' else w if align == 'right' else 0)
        ly = int(y) + i * lh
        if outline is not None:
            o = scale
            for dx in (-o, 0, o):
                for dy in (-o, 0, o):
                    if dx or dy:
                        _stamp(canvas, m, lx + dx, ly + dy, outline)
        if shadow is not None:
            _stamp(canvas, m, lx + scale, ly + scale, shadow)
        _stamp(canvas, m, lx, ly, color)
    return maxw


def _stamp(canvas, m, x, y, color):
    h, w = m.shape
    x0, y0 = max(0, x), max(0, y)
    x1, y1 = min(canvas.w, x + w), min(canvas.h, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    sub = m[y0 - y:y1 - y, x0 - x:x1 - x]
    canvas.a[y0:y1, x0:x1][sub] = col(color)
